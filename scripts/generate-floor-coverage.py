#!/usr/bin/env python3
"""Generate native 3D floor footprints from the reviewed, asset-free coverage maps."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def generate():
    document = json.loads((ROOT / 'data/world3d-floor-coverage.json').read_text(encoding='utf-8'))
    assert document['format'] == 1
    lines = ['/* Generated by scripts/generate-floor-coverage.py. Do not edit. */',
             '#ifndef IMPERA_FLOOR_COVERAGE_DEFAULTS_H', '#define IMPERA_FLOOR_COVERAGE_DEFAULTS_H',
             'typedef struct { uint16_t map; int8_t level; unsigned char cells[256]; } Floor3DDefault;',
             'static const Floor3DDefault floor3dDefaults[] = {']
    previous = (0, -2)
    for profile in document['profiles']:
        key = profile['map'], profile['floor']
        assert previous < key and 1 <= key[0] <= 32 and key[1] in (-1, 1, 2, 3)
        previous = key
        rows = profile['rows']
        assert len(rows) == 32 and all(len(row) == 32 for row in rows)
        values = [{'.': 0, '#': 1, 'o': 3}[cell] for row in rows for cell in row]
        packed = [sum(values[i+j] << (2*j) for j in range(4)) for i in range(0, 1024, 4)]
        lines.append(f'    /* {profile["name"]}, floor {key[1]}. */')
        lines.append(f'    {{{key[0]}, {key[1]}, {{')
        for i in range(0, 256, 16):
            lines.append('        ' + ', '.join(f'0x{v:02x}' for v in packed[i:i+16]) + ',')
        lines.append('    }},')
    lines.extend(['};', '#endif', ''])
    return '\n'.join(lines)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'src/mod/floor_coverage_defaults.h'
    result = generate().encode('utf-8')
    if args.check:
        if not target.exists() or target.read_bytes() != result:
            parser.exit(1, '3D floor coverage stale; run python scripts/generate-floor-coverage.py\n')
    else:
        target.write_bytes(result)
