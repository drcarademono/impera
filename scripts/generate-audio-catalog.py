#!/usr/bin/env python3
"""Generate authoring/export recipes from the engine's sound rules and DOS tables."""
import pathlib, re
root=pathlib.Path(__file__).resolve().parents[1]
source=(root/'src/vars.c').read_text(encoding='utf-8')
def table(name):
    body=re.search(r'\b'+name+r'\[[^]]+\]\s*=\s*\{([^}]+)',source).group(1)
    return [int(x,0) for x in re.findall(r'-?0x[0-9a-fA-F]+|-?\d+',body)]
rules={}
for params,file,id,kind in re.findall(r'\{\s*\{([^{}]+)\},\s*"([^"]+)",\s*(\d+), SFX_TYPE_(\w+)\s*\}',(root/'src/audio/sfx_map.h').read_text(encoding='utf-8')):
    rules.setdefault(int(id),(file,kind,[int(x) for x in params.split(',')]))
names={'chime':'Clock chime','blackapp':'Blackthorn apparition','sceptuse':'Sceptre activation','shadowin':'Shadowlord arrival','gatein':'Gate arrival','endmoon':'Moonstone removal','spiritin':'Spirit apparition','air':'Air spell','watrfall':'Waterfall','regurgit':'Regurgitation','introhit':'Introduction impact','shiphit':'Ship impact','tickhigh':'Clock tick (high)','ticklow':'Clock tick (low)','denyhi':'Denied (high)','denylo':'Denied (low)','foefire':'Enemy fire','trapfall':'Trapdoor fall','gemshard':'Gem / shard','shrine1':'Shrine ritual (rising)','shrine2':'Shrine ritual (falling)','mirror':'Mirror breaking','shake':'Earthquake','title1':'Title reveal','title2':'Subtitle reveal'}
names.update({'step0':'Footstep (first)', 'step1':'Footstep (second)', 'dunstep0':'Dungeon footstep 1', 'dunstep1':'Dungeon footstep 2', 'dunstep2':'Dungeon footstep 3', 'dunstep3':'Dungeon footstep 4', 'shop0':'Shop confirmation 1', 'shop1':'Shop confirmation 2', 'shop2':'Shop confirmation 3', 'victory1':'Victory phrase 1', 'victory2':'Victory phrase 2', 'burst1':'Burst (short)', 'burst2':'Burst (long)'})
contexts={'town.c':'Location interactions', 'cast.c':'Spellcasting', 'cast2.c':'Spellcasting and shrine rituals', 'comsubs.c':'Combat actions', 'blckthrn.c':'Blackthorn encounters', '4000.c':'Ambience and instruments', '6000.c':'Combat preparation and outcomes', 'intro.c':'Introduction and title', 'outsubs.c':'World events', 'font.c':'Character creation', 'endgame.c':'Final rescue', 'sjog.c':'Combat', 'dungeon.c':'Dungeon exploration', 'mainout.c':'World exploration'}
uses={}
functions={'PULSE':'ULTIMA_2192_AudioPulse','NOISE':'ULTIMA_223c_AudioWhiteNoise','TONE':'ULTIMA_22c0_AudioTone','SWEEP':'ULTIMA_43ae_AudioSweepTone'}
for id,(_,kind,p) in rules.items():
    found=[]
    # Filesystem enumeration differs between platforms and fresh checkouts.
    for path in sorted((root/'src').glob('*.c')):
        for args in re.findall(r'\b'+functions.get(kind,'__none__')+r'\(([^()]*)\)',path.read_text(encoding='utf-8')):
            try: values=[int(x.strip(),0) for x in args.split(',')]
            except ValueError: continue
            if values==p[:len(values)]: found.append(contexts.get(path.name,path.stem))
    uses[id]=', '.join(dict.fromkeys(found))
lines=['/* Generated by scripts/generate-audio-catalog.py; recipes share vanilla engine tables. */', '#ifndef IMPERA_AUDIO_CATALOG_H','#define IMPERA_AUDIO_CATALOG_H','typedef struct {int kind,p[5];} AudioRecipe;','typedef struct {const char *name,*file,*uses;unsigned first,count;} AudioCatalog;']
recipes=[];entries=[]
for id,(file,kind,p) in rules.items():
    steps=[];stem=file[:-4];name=names.get(stem,stem.capitalize())
    if kind!='UNMAPPED': steps=[(['PULSE','NOISE','TONE','SWEEP'].index(kind),p)]
    if 20<=id<=29: uses[id]='Location harpsichords';name=f'Harpsichord note {id-19}';steps=[(0,[table('D_2746')[id-20],1,4000,20000,-4])]
    if 30<=id<=38: uses[id]='Ambient lute music';name=f'Lute note {id-29}';steps=[(0,[table('D_6a36')[id-30],1,2000,20000,-10])]
    if 39<=id<=46:
        i=id-38;uses[id]='Spellcasting (complete paired effect)';name=f'Spell circle {i} (paired tones)'
        steps=[(0,[table('D_4af6')[i],1,i*4000+10000,table('D_4b08')[i],table('D_4b2c')[i]]),(0,[table('D_4af6')[i],1,i*4000+10000,table('D_4b1a')[i],-table('D_4b2c')[i]])]
    if 49<=id<=54:
        i=id-49;uses[id]='Blackthorn encounters';name=f'Blackthorn phrase {i+1}';steps=[(0,[table('D_3720')[i],1,table('D_372c')[i],table('D_3738')[i],table('D_3744')[i]])]
    if 55<=id<=61:
        i=id-55;uses[id]='Shrine ritual';name=f'Ritual phrase {i+1}';steps=[(0,[table('D_4be6')[i],1,table('D_4bf4')[i],table('D_4c02')[i],table('D_4c10')[i]])]
    if 62<=id<=67:
        i=id-62;uses[id]='World apparitions';name=f'Apparition phrase {i+1}';steps=[(0,[table('D_3a26')[i],1,5000,200,13])]
    if id in (106,107): steps=[(3,[3200,3500,1,12 if id==106 else 4,0])];name=f'Drip variant {id-104}'
    if 109<=id<=111:
        freq=2640 if id==109 else 2700 if id==110 else 3100;dur=150 if id==111 else 200
        steps=[(0,[freq,1,dur,w,0]) for w in list(range(2000,25000,50))+list(range(25000,2000,-50))]
    if id==112: steps=[(1,[40,120,limit,0,0]) for limit in range(2000,20000,1000)]
    if 109<=id<=111: uses[id]='Gem / shard ritual' if id==109 else 'Shrine ritual (complete sequence)'
    if id==112: uses[id]='Breaking location mirrors'
    if id>=114: uses[id]='Title-screen reveal (recording only)'
    entries.append(f'    {{"{name}","{file}","{uses[id] or "Vanilla gameplay events"}",{len(recipes)},{len(steps)}}}, /* {id} */')
    recipes+=steps
lines+=['static const AudioRecipe audioRecipes[] = {']+['    {'+str(k)+',{'+','.join(map(str,p))+'}},' for k,p in recipes]+['};','static const AudioCatalog audioCatalog[] = {']+entries+['};','#endif','']
out='\n'.join(lines)
path=root/'src/audio/audio_catalog.h'
if '--check' in __import__('sys').argv:
    if path.read_text(encoding='utf-8')!=out: raise SystemExit('Audio catalog stale; run scripts/generate-audio-catalog.py')
else:path.write_text(out, encoding='utf-8', newline='\n')
