#!/usr/bin/env python3
"""Regenerate embedded alternate tilesets; native builds do not require Python."""
import argparse
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
def zhelkas_png():
    data = (ROOT / 'textures/tilesets/TILES_Zhelkas.16').read_bytes()
    wanted = int.from_bytes(data[:4], 'little')
    if wanted != 65536:
        raise ValueError('Zhelkas tileset must decode to 512 DOS tiles')
    table = [bytes([i]) for i in range(256)] + [b'', b'']
    width, pos, previous = 9, 32, b''
    raw = bytearray()
    while len(raw) < wanted:
        if pos + width > len(data) * 8:
            raise ValueError('Truncated Zhelkas tileset')
        code = sum(((data[(pos+i)//8] >> ((pos+i)%8)) & 1) << i for i in range(width))
        pos += width
        if code == 256:
            table = [bytes([i]) for i in range(256)] + [b'', b'']
            width, previous = 9, b''
            continue
        if code < len(table) and table[code]:
            entry = table[code]
        elif code == len(table) and previous:
            entry = previous + previous[:1]
        else:
            raise ValueError('Invalid Zhelkas LZW code')
        raw.extend(entry)
        if previous and len(table) < 4096:
            table.append(previous + entry[:1])
            if len(table) == 1 << width and width < 12:
                width += 1
        previous = entry
    if len(raw) != wanted:
        raise ValueError('Incorrect Zhelkas decoded size')
    colors = [(0,0,0),(0,0,170),(0,170,0),(0,170,170),(170,0,0),(170,0,170),
              (170,85,0),(170,170,170),(85,85,85),(85,85,255),(85,255,85),(85,255,255),
              (255,85,85),(255,85,255),(255,255,85),(255,255,255)]
    rows = bytearray()
    for y in range(256):
        rows.append(0)
        for x in range(512):
            tile = (y//16)*32 + x//16
            value = raw[tile*128 + (y%16)*8 + (x%16)//2]
            rows.extend(colors[value & 15 if x%2 else value >> 4])
    def chunk(name, data):
        return struct.pack('>I',len(data))+name+data+struct.pack('>I',zlib.crc32(name+data))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR',struct.pack('>IIBBBBB',512,256,8,2,0,0,0))
            + chunk(b'IDAT',zlib.compress(rows,9)) + chunk(b'IEND',b''))

def png_payload(data):
    """Validate our generated RGB PNG and compare pixels independently of zlib."""
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError('Invalid PNG signature')
    offset, header, compressed, ended = 8, None, bytearray(), False
    while offset < len(data):
        if len(data) - offset < 12:
            raise ValueError('Truncated PNG chunk')
        size = struct.unpack_from('>I', data, offset)[0]
        end = offset + 12 + size
        if end > len(data):
            raise ValueError('Truncated PNG data')
        name = data[offset+4:offset+8]
        payload = data[offset+8:end-4]
        crc = struct.unpack_from('>I', data, end-4)[0]
        if zlib.crc32(name + payload) != crc:
            raise ValueError('Invalid PNG checksum')
        if name == b'IHDR':
            if header is not None or offset != 8 or size != 13:
                raise ValueError('Invalid PNG header')
            header = payload
        elif name == b'IDAT':
            compressed.extend(payload)
        elif name == b'IEND':
            if size or end != len(data):
                raise ValueError('Invalid PNG end')
            ended = True
        else:
            raise ValueError('Unexpected generated PNG chunk')
        offset = end
    if not ended or header != struct.pack('>IIBBBBB', 512, 256, 8, 2, 0, 0, 0):
        raise ValueError('Invalid generated PNG dimensions or format')
    decoder = zlib.decompressobj()
    pixels = decoder.decompress(compressed) + decoder.flush()
    if not decoder.eof or decoder.unused_data or len(pixels) != 256 * (1 + 512 * 3):
        raise ValueError('Invalid PNG pixel data')
    # The generator uses unfiltered rows. Preserve that contract as well as RGB.
    if any(pixels[y * (1 + 512 * 3)] != 0 for y in range(256)):
        raise ValueError('Unexpected generated PNG filter')
    return header, pixels

zhelkas = ROOT / 'textures/tilesets/Ultima_5_Tiles_Zhelkas.png'
zhelkas_data = zhelkas_png()
if '--check' in __import__('sys').argv:
    try:
        # Compressor versions may encode identical pixels differently. The
        # checked-in PNG remains authoritative for the embedded byte check below.
        valid = zhelkas.exists() and png_payload(zhelkas.read_bytes()) == png_payload(zhelkas_data)
    except (ValueError, zlib.error):
        valid = False
    if not valid:
        raise SystemExit('Zhelkas PNG is stale; run python scripts/embed-tilesets.py')
else:
    zhelkas.write_bytes(zhelkas_data)
sources = sorted((ROOT / 'textures/tilesets').glob('*.png'))
lines = ['/* Generated by scripts/embed-tilesets.py. Do not edit by hand. */',
         '#ifndef IMPERA_TILESET_ASSETS_H', '#define IMPERA_TILESET_ASSETS_H']
for index, source in enumerate(sources):
    data = source.read_bytes()
    lines.append(f'static const unsigned char tileset_png_{index}[] = {{')
    for offset in range(0, len(data), 16):
        lines.append('    ' + ','.join(f'0x{value:02x}' for value in data[offset:offset+16]) + ',')
    lines.append('};')
lines.append('static const struct { const char *name; const unsigned char *data; int size; } tileset_pngs[] = {')
for index, source in enumerate(sources):
    lines.append(f'    {{"{source.name}", tileset_png_{index}, sizeof(tileset_png_{index})}},')
lines.extend(['};', '#endif', ''])
content = '\n'.join(lines)
target = ROOT / 'src/graphics/tileset_assets.h'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != content:
        parser.error('Tileset bytes are stale; run python scripts/embed-tilesets.py')
else:
    target.write_text(content)
