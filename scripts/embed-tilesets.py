#!/usr/bin/env python3
"""Regenerate embedded alternate tilesets; native builds do not require Python."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sources = sorted((ROOT / 'textures/tilesets').glob('*.png'))
lines = ['/* Generated by scripts/embed-tilesets.py. Do not edit by hand. */',
         '#ifndef IMPERA_TILESET_ASSETS_H', '#define IMPERA_TILESET_ASSETS_H']
for index, source in enumerate(sources):
    data = source.read_bytes()
    lines.append(f'static const unsigned char tileset_png_{index}[] = {{')
    for offset in range(0, len(data), 16):
        lines.append('    ' + ','.join(f'0x{value:02x}' for value in data[offset:offset+16]) + ',')
    lines.append('};')
lines.append('static const struct { const char *name; const unsigned char *data; int size; } tileset_pngs[] = {')
for index, source in enumerate(sources):
    lines.append(f'    {{"{source.name}", tileset_png_{index}, sizeof(tileset_png_{index})}},')
lines.extend(['};', '#endif', ''])
content = '\n'.join(lines)
target = ROOT / 'src/graphics/tileset_assets.h'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != content:
        parser.error('Tileset bytes are stale; run python scripts/embed-tilesets.py')
else:
    target.write_text(content)
